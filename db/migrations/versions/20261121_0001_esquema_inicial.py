def _ejecutar(bloque: str) -> None:
    """Ejecuta un bloque con varias sentencias, respetando los cuerpos $$ ... $$ de plpgsql."""
    sentencias, actual, en_cuerpo = [], [], False
    for linea in bloque.splitlines():
        actual.append(linea)
        if linea.count("$$") % 2 == 1:
            en_cuerpo = not en_cuerpo
        if not en_cuerpo and linea.rstrip().endswith(";"):
            sentencias.append("\n".join(actual))
            actual = []
    for sentencia in sentencias:
        if sentencia.strip():
            op.execute(sentencia)


